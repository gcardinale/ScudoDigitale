namespace ScudoDigitale.Core;

/// <summary>
/// Severity of a <see cref="Finding"/>. Higher numeric values are more severe,
/// so values can be compared and sorted directly.
/// </summary>
public enum Severity
{
    /// <summary>Informational: no direct risk, worth knowing.</summary>
    Info = 0,

    /// <summary>Low risk.</summary>
    Low = 1,

    /// <summary>Medium risk.</summary>
    Medium = 2,

    /// <summary>High risk.</summary>
    High = 3,

    /// <summary>Critical risk, including every vulnerability listed in CISA KEV.</summary>
    Critical = 4,
}
