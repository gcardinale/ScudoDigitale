namespace ScudoDigitale.Core;

/// <summary>
/// What a check needs to be allowed to run against a target (ADR-004).
/// </summary>
public enum ScopeRequirement
{
    /// <summary>Reads only public information: allowed on any target.</summary>
    Passive,

    /// <summary>
    /// Actively probes the target: allowed only after <see cref="IScopeGuard"/> confirms that
    /// the target is the user's own local network or a domain with verified ownership.
    /// </summary>
    ActiveOwnedOnly,
}
