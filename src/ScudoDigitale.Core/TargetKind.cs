namespace ScudoDigitale.Core;

/// <summary>
/// Kind of <see cref="Target"/> a check applies to.
/// </summary>
public enum TargetKind
{
    /// <summary>An internet domain, for example <c>example.com</c>.</summary>
    Domain,

    /// <summary>An email address.</summary>
    EmailAddress,

    /// <summary>A website, identified by its URL.</summary>
    Website,

    /// <summary>A local network, identified by its address range (for example <c>192.168.1.0/24</c>).</summary>
    Network,

    /// <summary>The computer running the program and its radio environment (Wi-Fi, Bluetooth).</summary>
    LocalMachine,
}
