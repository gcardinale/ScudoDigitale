namespace ScudoDigitale.Core;

/// <summary>
/// How sure a check is about a <see cref="Finding"/>. Higher numeric values are more certain.
/// </summary>
public enum Confidence
{
    /// <summary>The condition could not be confirmed and must be verified by hand.</summary>
    ToBeVerified = 0,

    /// <summary>The condition is inferred (for example from a banner or a manufacturer id).</summary>
    Probable = 1,

    /// <summary>The condition was observed directly.</summary>
    Certain = 2,
}
